/**
 * Verifies the gallery UI renders images produced by the real generation
 * pipeline (mock provider), including lightbox and delete via the UI.
 */
const { spawn } = require("child_process");
const http = require("http");
const os = require("os");
const path = require("path");
const WebSocket = require("ws");

const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
const APP = "http://127.0.0.1:8765/ui.html";
const API = "http://127.0.0.1:8765";
const MOCK = "http://127.0.0.1:8790/v1";
const PORT = 9336;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const get = (url) => new Promise((res, rej) => {
  http.get(url, (r) => { let d = ""; r.on("data", c => d += c); r.on("end", () => res(d)); }).on("error", rej);
});

const api = async (method, p, body) => {
  const data = body ? JSON.stringify(body) : null;
  return new Promise((resolve, reject) => {
    const r = http.request(API + p, {
      method,
      headers: { "Content-Type": "application/json", ...(data ? { "Content-Length": Buffer.byteLength(data) } : {}) },
    }, (resp) => { let d = ""; resp.on("data", c => d += c); resp.on("end", () => { try { resolve(JSON.parse(d || "{}")); } catch (e) { resolve(d); } }); });
    r.on("error", reject);
    if (data) r.write(data);
    r.end();
  });
};

const waitJobs = async (pid, min, timeout = 60) => {
  const end = Date.now() + timeout * 1000;
  while (Date.now() < end) {
    const jobs = await api("GET", "/api/jobs/" + pid);
    if (Array.isArray(jobs)) {
      const pending = jobs.filter(j => ["queued", "running"].includes(j.status));
      if (!pending.length && jobs.length >= min) return jobs;
    }
    await sleep(1000);
  }
  return api("GET", "/api/jobs/" + pid);
};

(async () => {
  const results = [];
  const check = (name, ok, detail = "") => {
    results.push({ name, ok });
    console.log((ok ? "PASS  " : "FAIL  ") + name + (ok ? "" : "  -> " + String(detail).slice(0, 250)));
  };

  // seed data through the real pipeline
  const preset = await api("POST", "/api/presets", {
    name: "UI Mock Preset",
    logic_provider: "mock", logic_url: MOCK, logic_key: "test", logic_model: "mock-logic",
    image_provider: "mock", image_url: MOCK, image_key: "test", image_model: "mock-image",
    default_aspect_ratio: "1:1", default_resolution: "1024x1024", default_count: 1,
    system_prompt: "plan images",
  });
  const project = await api("POST", "/api/projects", { name: "Gallery UI Test", description: "", instructions: "" });
  await api("PUT", "/api/projects/" + project.id, { name: "Gallery UI Test", description: "", instructions: "", active_preset_id: preset.id });
  const conv = await api("POST", "/api/projects/" + project.id + "/conversations", { title: "gallery" });

  // chat -> plan -> jobs -> worker -> images
  await api("POST", "/api/conversations/" + conv.id + "/messages", { content: "generate fox images" });
  await waitJobs(project.id, 2);

  const gallery = await api("GET", "/api/gallery/" + project.id);
  check("seed: images generated by pipeline", Array.isArray(gallery) && gallery.length >= 2,
    Array.isArray(gallery) ? gallery.length : gallery);

  // now open the UI
  const userData = path.join(os.tmpdir(), "imggen-gallery-test");
  const chrome = spawn(CHROME, ["--headless=new", "--disable-gpu", "--no-sandbox",
    `--remote-debugging-port=${PORT}`, `--user-data-dir=${userData}`, "about:blank"], { stdio: "ignore" });

  let ws;
  try {
    let t = null;
    for (let i = 0; i < 40; i++) { await sleep(500); try { t = JSON.parse(await get(`http://127.0.0.1:${PORT}/json/version`)); break; } catch (e) {} }
    ws = new WebSocket(t.webSocketDebuggerUrl, { perMessageDeflate: false, maxPayload: 512 * 1024 * 1024 });
    await new Promise((res, rej) => { ws.on("open", res); ws.on("error", rej); });

    let id = 0;
    const send = (method, params = {}, sessionId) => new Promise((resolve, reject) => {
      const myId = ++id;
      const h = (data) => { const m = JSON.parse(data); if (m.id === myId) { ws.off("message", h); m.error ? reject(new Error(JSON.stringify(m.error))) : resolve(m.result); } };
      ws.on("message", h);
      const msg = { id: myId, method, params };
      if (sessionId) msg.sessionId = sessionId;
      ws.send(JSON.stringify(msg));
    });

    const { targetId } = await send("Target.createTarget", { url: "about:blank" });
    const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
    const ev = async (expression) => {
      const r = await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true }, sessionId);
      if (r.exceptionDetails) throw new Error("JS ERROR: " + (r.exceptionDetails.exception?.description || r.exceptionDetails.text));
      return r.result.value;
    };

    await send("Runtime.enable", {}, sessionId);
    await send("Page.enable", {}, sessionId);
    await ev(`window.__errs=[]; window.addEventListener('error',e=>window.__errs.push(String(e.message))); true;`);
    await send("Page.navigate", { url: APP }, sessionId);
    await sleep(4500);

    check("page loaded without JS errors", (await ev(`JSON.stringify(window.__errs||[])`)) === "[]",
      await ev(`JSON.stringify(window.__errs||[])`));

    // select the seeded project
    await ev(`
      (async () => {
        const list = await (await fetch('/api/projects')).json();
        const p = list.find(x => x.name === 'Gallery UI Test');
        await window.selectProject(p.id);
      })();
      true;
    `);
    await sleep(2500);

    const badge = await ev(`document.getElementById('project-badge').textContent`);
    check("project selected in UI", badge === "Gallery UI Test", badge);

    // open gallery
    await ev(`document.getElementById('switch-gallery').click(); true`);
    await sleep(2000);

    const cards = await ev(`document.querySelectorAll('#gallery-grid .card').length`);
    check("gallery renders image cards", cards >= 2, cards);

    // images actually load (not broken)
    await sleep(1500);
    const loaded = await ev(`
      Array.from(document.querySelectorAll('#gallery-grid img'))
        .filter(i => i.complete && i.naturalWidth > 0).length
    `);
    check("gallery images load successfully", loaded >= 2, loaded);

    // model badge rendered
    const badges = await ev(`Array.from(document.querySelectorAll('#gallery-grid .model-badge')).map(b=>b.textContent)`);
    check("model badge shows generating model", badges.length > 0 && badges[0] === "mock-image", badges);

    // lightbox opens
    await ev(`document.querySelector('#gallery-grid img').click(); true`);
    await sleep(900);
    const lb = await ev(`document.getElementById('lightbox').style.display`);
    check("lightbox opens on image click", lb === "flex", lb);

    await ev(`document.getElementById('lightbox').click(); true`);
    await sleep(700);
    const lbClosed = await ev(`document.getElementById('lightbox').style.display`);
    check("lightbox closes", lbClosed === "none", lbClosed);

    // delete via UI (confirm auto-accept)
    await ev(`window.confirm = () => true; true`);
    const before = await ev(`document.querySelectorAll('#gallery-grid .card').length`);
    await ev(`
      (async () => {
        const imgs = await (await fetch('/api/gallery/' + window.STATE.activeProjectId)).json();
        await window.delImg(imgs[0].id);
      })();
      true;
    `);
    await sleep(2500);
    const after = await ev(`document.querySelectorAll('#gallery-grid .card').length`);
    check("delete removes card from gallery", after === before - 1, { before, after });

    const errs = await ev(`JSON.stringify(window.__errs||[])`);
    check("no JS errors during gallery flow", errs === "[]", errs);

  } catch (e) {
    check("harness completed", false, e.message);
  } finally {
    try { ws && ws.close(); } catch (e) {}
    try { chrome.kill(); } catch (e) {}
  }

  // cleanup
  await api("DELETE", "/api/projects/" + project.id);
  await api("DELETE", "/api/presets/" + preset.id);

  const passed = results.filter(r => r.ok).length;
  console.log("\n" + "=".repeat(60));
  console.log(`RESULT: ${passed}/${results.length} passed`);
  process.exit(passed === results.length ? 0 : 1);
})();
